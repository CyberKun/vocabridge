"""Turn accepted hypotheses into RDF data and SHACL shapes, and validate one against the other.

Only hypotheses with status ``accepted`` are used. Proposed or rejected mappings are never
written to the output graph.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import quote

from rdflib import BNode, Graph, Literal, Namespace, URIRef
from rdflib.collection import Collection
from rdflib.namespace import DCTERMS, PROV, RDF, XSD

from .hypotheses import ACCEPTED, IRI, MappingSet
from .profiling import DatasetProfile, read_records
from .text import local_name

SH = Namespace("http://www.w3.org/ns/shacl#")

_TRUE = {"true", "yes", "y", "t", "1"}
_FALSE = {"false", "no", "n", "f", "0"}


class MappingNotReadyError(ValueError):
    """Raised when a mapping file has nothing accepted that can be generated."""


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-") or "resource"


def resource_iri(base_iri: str, class_iri: str, key: str) -> URIRef:
    """Mint ``{base}{class-slug}/{key}`` so references across datasets line up."""
    return URIRef(f"{base_iri}{_slug(local_name(class_iri))}/{quote(key.strip(), safe='')}")


def _literal(value: str, datatype: str | None) -> Literal:
    value = value.strip()
    if datatype == str(XSD.boolean):
        lowered = value.lower()
        if lowered in _TRUE:
            value = "true"
        elif lowered in _FALSE:
            value = "false"
    if datatype and datatype != str(XSD.string):
        return Literal(value, datatype=URIRef(datatype))
    return Literal(value)


def _namespace(iri: str) -> str:
    return iri[: len(iri) - len(local_name(iri))]


def _bind_common(graph: Graph, mapping: MappingSet) -> None:
    if mapping.subject.term:
        graph.bind("vocab", Namespace(_namespace(mapping.subject.term)))
    graph.bind("data", Namespace(mapping.base_iri))


def _require_ready(mapping: MappingSet) -> None:
    if mapping.subject.status != ACCEPTED or not mapping.subject.term:
        raise MappingNotReadyError(
            "The subject class hypothesis is not accepted. Review it first, e.g. "
            "`vocabridge review mapping.json --accept __subject__`."
        )
    if not mapping.accepted_fields():
        raise MappingNotReadyError("No field hypotheses are accepted yet; nothing to generate.")


def build_graph(mapping: MappingSet, records: list[dict[str, str]],
                provenance: bool = True) -> Graph:
    _require_ready(mapping)
    subject_class = mapping.subject.term
    accepted = mapping.accepted_fields()

    graph = Graph()
    _bind_common(graph, mapping)
    graph.bind("prov", PROV)
    graph.bind("dcterms", DCTERMS)
    for index, row in enumerate(records, start=1):
        key = (row.get(mapping.id_field) or "").strip() if mapping.id_field else ""
        subject = resource_iri(mapping.base_iri, subject_class, key or f"row-{index}")
        graph.add((subject, RDF.type, URIRef(subject_class)))
        for h in accepted:
            raw = row.get(h.field)
            if raw is None or raw.strip() == "":
                continue
            if h.value_kind == IRI:
                target_cls = h.target_class or subject_class
                graph.add((subject, URIRef(h.term), resource_iri(mapping.base_iri, target_cls, raw)))
            else:
                graph.add((subject, URIRef(h.term), _literal(raw, h.datatype)))

    if provenance:
        run = URIRef(f"{mapping.base_iri}run/{_slug(Path(mapping.dataset).stem)}")
        graph.add((run, RDF.type, PROV.Activity))
        graph.add((run, PROV.used, Literal(mapping.dataset)))
        graph.add((run, PROV.endedAtTime,
                   Literal(datetime.now(timezone.utc).isoformat(timespec="seconds"),
                           datatype=XSD.dateTime)))
        graph.add((run, DCTERMS.description, Literal(
            f"Generated by vocabridge from {len(accepted)} accepted mapping hypotheses "
            f"over {len(records)} rows.")))
        reviewers = sorted({h.review.reviewer for h in mapping.all()
                            if h.status == ACCEPTED and h.review.reviewer})
        for reviewer in reviewers:
            graph.add((run, PROV.wasAssociatedWith, Literal(reviewer)))
    return graph


def dataset_path(mapping: MappingSet, mapping_file: str | Path | None = None) -> Path:
    """Resolve the dataset path, which is stored relative to the mapping file."""
    path = Path(mapping.dataset)
    if not path.is_absolute() and mapping_file is not None:
        path = Path(mapping_file).parent / path
    return path


def generate_rdf(mapping: MappingSet, mapping_file: str | Path | None = None,
                 provenance: bool = True) -> Graph:
    records = read_records(dataset_path(mapping, mapping_file), delimiter=mapping.delimiter)
    return build_graph(mapping, records, provenance=provenance)


def build_shapes(mapping: MappingSet, profile: DatasetProfile | None = None) -> Graph:
    """Create one SHACL NodeShape for the subject class from the accepted field mappings.

    If a profile is given, fields with no missing values get ``sh:minCount 1``.
    """
    _require_ready(mapping)
    subject_class = URIRef(mapping.subject.term)
    shapes = Graph()
    _bind_common(shapes, mapping)
    shapes.bind("sh", SH)
    shapes.bind("xsd", XSD)
    node_shape = URIRef(f"{mapping.base_iri}shapes/{local_name(str(subject_class))}Shape")
    shapes.add((node_shape, RDF.type, SH.NodeShape))
    shapes.add((node_shape, SH.targetClass, subject_class))

    complete = set()
    if profile is not None:
        complete = {f.name for f in profile.fields if f.is_complete}

    for h in mapping.accepted_fields():
        prop = BNode()
        shapes.add((node_shape, SH.property, prop))
        shapes.add((prop, SH.path, URIRef(h.term)))
        shapes.add((prop, SH.name, Literal(h.term_label or local_name(h.term))))
        shapes.add((prop, SH.description, Literal(f"From source field '{h.field}'")))
        shapes.add((prop, SH.maxCount, Literal(1)))
        if h.field in complete:
            shapes.add((prop, SH.minCount, Literal(1)))
        if h.value_kind == IRI:
            shapes.add((prop, SH.nodeKind, SH.IRI))
        elif h.datatype:
            shapes.add((prop, SH.datatype, URIRef(h.datatype)))

    # Each row must be identifiable by exactly the properties we declare plus rdf:type.
    ignored = BNode()
    Collection(shapes, ignored, [RDF.type])
    shapes.add((node_shape, SH.ignoredProperties, ignored))
    shapes.add((node_shape, SH.closed, Literal(True)))
    return shapes


@dataclass
class ValidationResult:
    conforms: bool
    report_text: str
    report_graph: Graph


def validate(data: Graph, shapes: Graph) -> ValidationResult:
    from pyshacl import validate as shacl_validate

    conforms, report_graph, report_text = shacl_validate(
        data, shacl_graph=shapes, inference="none", abort_on_first=False, allow_warnings=True
    )
    return ValidationResult(bool(conforms), str(report_text), report_graph)
